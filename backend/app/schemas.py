"""
Request/response shapes. FastAPI uses these to validate incoming JSON,
which replaces the manual checks in the Tkinter forms (required fields,
email format, numeric price, date order).
"""
from datetime import date
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, EmailStr, Field, computed_field, model_validator


# ---------- Auth ----------
class Token(BaseModel):
    access_token: str
    token_type: str = "bearer"


# ---------- Users ----------
class UserCreate(BaseModel):
    username: str = Field(min_length=1, max_length=50)
    fullname: str = Field(min_length=1, max_length=100)
    role: Literal["Admin", "User"]
    email: EmailStr
    password: str = Field(min_length=6)


class UserOut(BaseModel):
    """What the API sends back. Note: no password field at all."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    username: str
    fullname: str
    role: str
    email: str


# ---------- Products ----------
class ProductBase(BaseModel):
    product_name: str = Field(min_length=1, max_length=100)
    price: float = Field(gt=0)
    quantity: int = Field(ge=0)
    date_added: date
    expiry_date: date

    @model_validator(mode="after")
    def expiry_after_added(self):
        if self.expiry_date < self.date_added:
            raise ValueError("Expiry Date cannot be before Date Added.")
        return self


class ProductCreate(ProductBase):
    """Batch ID is generated by the server, so it isn't sent in."""


class ProductUpdate(ProductBase):
    pass


class ProductOut(ProductBase):
    model_config = ConfigDict(from_attributes=True)

    id: int
    batch_id: str


class ExpiryAlert(BaseModel):
    batch_id: str
    product_name: str
    expiry_date: date
    days_left: int
    status: Literal["expired", "expiring_soon"]
    message: str


class LowStockAlert(BaseModel):
    product_name: str
    quantity: int     # total across all batches of this product
    threshold: int
    message: str


# ---------- Orders ----------
class OrderBase(BaseModel):
    """One line from the client's sales ledger."""

    order_date: date
    customer_name: str = Field(min_length=1, max_length=100)
    product_name: str = Field(min_length=1, max_length=100)
    cartons: Optional[float] = Field(default=None, gt=0)  # blank or fractional in the ledger
    amount: float = Field(ge=0)          # total price of the order
    amount_paid: float = Field(ge=0, default=0)
    notes: Optional[str] = Field(default=None, max_length=255)

    @model_validator(mode="after")
    def paid_not_more_than_amount(self):
        if self.amount_paid > self.amount:
            raise ValueError("Amount paid cannot be more than the order amount.")
        return self


class OrderCreate(OrderBase):
    pass


class OrderUpdate(OrderBase):
    pass


class OrderOut(OrderBase):
    model_config = ConfigDict(from_attributes=True)

    id: int

    @computed_field
    @property
    def balance(self) -> float:
        """How much the customer still owes on this order."""
        return round(self.amount - self.amount_paid, 2)

    @computed_field
    @property
    def status(self) -> str:
        if self.amount_paid >= self.amount:
            return "Paid"
        if self.amount_paid > 0:
            return "Part paid"
        return "Owing"
